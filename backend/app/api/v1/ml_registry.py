from __future__ import annotations

from typing import Annotated, Optional
from fastapi import APIRouter, Depends, Query, status
from sqlalchemy.orm import Session

from backend.app.dependencies import get_current_user, get_db, require_roles
from backend.app.models.schema import MLModelType, TrainingStatus, User, UserRole
from backend.app.schemas.ml_registry import (
    FeatureSetCreateRequest,
    FeatureSetResponse,
    MLModelListResponse,
    MLModelResponse,
    ModelTrainingRunListResponse,
    ModelTrainingRunResponse,
    ModelTrainingTriggerRequest,
)
from backend.app.services.ml_registry_service import MLRegistryService

router = APIRouter(prefix="/ml", tags=["9. Feature Sets & ML Registry"])


# --- Feature Sets (70-72) ---

@router.get("/feature-sets", response_model=list[FeatureSetResponse])
def list_feature_sets(
    current_user: Annotated[User, Depends(require_roles(UserRole.ADMIN, UserRole.ANALYST))],
    db: Annotated[Session, Depends(get_db)],
    model_type: Optional[MLModelType] = None,
    name: Optional[str] = None,
):
    """List registered feature Parquet sets (Tier 2)."""
    fsets = MLRegistryService.list_feature_sets(db, model_type=model_type, name=name)
    return [FeatureSetResponse.model_validate(f) for f in fsets]


@router.get("/feature-sets/{id}", response_model=FeatureSetResponse)
def get_feature_set_detail(
    id: int,
    current_user: Annotated[User, Depends(require_roles(UserRole.ADMIN, UserRole.ANALYST))],
    db: Annotated[Session, Depends(get_db)],
):
    """Get feature set details, schema metadata, and column list (Tier 2)."""
    fs = MLRegistryService.get_feature_set(db, id)
    return FeatureSetResponse.model_validate(fs)


@router.post("/feature-sets", response_model=FeatureSetResponse, status_code=status.HTTP_201_CREATED)
def register_feature_set(
    payload: FeatureSetCreateRequest,
    current_admin: Annotated[User, Depends(require_roles(UserRole.ADMIN))],
    db: Annotated[Session, Depends(get_db)],
):
    """Register feature Parquet dataset generated by feature pipeline (Worker / Admin only, Tier 2)."""
    fs = MLRegistryService.create_feature_set(db, payload, user_id=current_admin.id)
    return FeatureSetResponse.model_validate(fs)


