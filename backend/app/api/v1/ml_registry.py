# --- Training Runs (78-81) ---

@router.get("/training-runs", response_model=ModelTrainingRunListResponse)
def list_training_runs(
    current_user: Annotated[User, Depends(require_roles(UserRole.ADMIN, UserRole.ANALYST))],
    db: Annotated[Session, Depends(get_db)],
    model_type: Optional[MLModelType] = None,
    status: Optional[TrainingStatus] = None,
    page: int = Query(1, ge=1),
    page_size: int = Query(20, ge=1, le=100),
):
    """List asynchronous ML model training runs (Tier 2)."""
    items, total = MLRegistryService.list_training_runs(
        db, model_type=model_type, status=status, page=page, page_size=page_size
    )
    return ModelTrainingRunListResponse(
        items=[ModelTrainingRunResponse.model_validate(r) for r in items],
        total=total,
        page=page,
        page_size=page_size,
    )


@router.post("/training-runs", response_model=ModelTrainingRunResponse, status_code=status.HTTP_201_CREATED)
def trigger_training_run(
    payload: ModelTrainingTriggerRequest,
    current_admin: Annotated[User, Depends(require_roles(UserRole.ADMIN))],
    db: Annotated[Session, Depends(get_db)],
):
    """Trigger background ML model training run (Admin only, Tier 2)."""
    run = MLRegistryService.trigger_training_run(db, payload, user_id=current_admin.id)
    return ModelTrainingRunResponse.model_validate(run)


