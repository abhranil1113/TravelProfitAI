"""
optimization/recommendations/rejection_reasons.py

Standardized diagnostic reason codes for unselected or invalid procurement opportunities.
"""

from enum import Enum


class RejectionReasonCode(str, Enum):
    NEGATIVE_CONTRIBUTION = "NEGATIVE_CONTRIBUTION"
    MOQ_EXCEEDS_BUDGET = "MOQ_EXCEEDS_BUDGET"
    MOQ_EXCEEDS_DEMAND = "MOQ_EXCEEDS_DEMAND"
    INSUFFICIENT_SUPPLIER_CAPACITY = "INSUFFICIENT_SUPPLIER_CAPACITY"
    DESTINATION_CAP_BINDING = "DESTINATION_CAP_BINDING"
    SUPPLIER_CAP_BINDING = "SUPPLIER_CAP_BINDING"
    CATEGORY_BUDGET_LIMIT = "CATEGORY_BUDGET_LIMIT"
    EXPIRED_OFFER = "EXPIRED_OFFER"
    INVALID_CURRENCY = "INVALID_CURRENCY"
    INVALID_COMMERCIAL_INPUT = "INVALID_COMMERCIAL_INPUT"
    NOT_SELECTED_BY_OPTIMAL_ALLOCATION = "NOT_SELECTED_BY_OPTIMAL_ALLOCATION"
